# Notes/commission.ps1
#
# Scans every VN dialogue file for asset calls (@img / @image / @sfx / @music)
# and writes Notes/asset_commission.md - what the writing asks for, and what
# still doesn't exist on disk.
#
# Run from anywhere:   powershell -File Notes\commission.ps1
#
# img  -> car/vn/img/<name>.png|webp|jpg|jpeg
# sfx  -> car/vn/sfx/<name>.ogg|wav|mp3
# music-> car/vn/sfx/<name>.ogg|wav|mp3   (music lives in the same folder)

$root   = Split-Path -Parent $PSScriptRoot
$dlgDir = Join-Path $root 'car\vn\dialogue'
$imgDir = Join-Path $root 'car\vn\img'
$sfxDir = Join-Path $root 'car\vn\sfx'
$outMd  = Join-Path $PSScriptRoot 'asset_commission.md'

$imgExt = @('png', 'webp', 'jpg', 'jpeg')
$sfxExt = @('ogg', 'wav', 'mp3')
$skip   = @('none', 'off', 'stop', 'black', 'white', '')

function Test-Asset($kind, $name) {
	if ($kind -eq 'img') {
		foreach ($e in $imgExt) { if (Test-Path (Join-Path $imgDir "$name.$e")) { return $true } }
	} else {
		foreach ($e in $sfxExt) { if (Test-Path (Join-Path $sfxDir "$name.$e")) { return $true } }
	}
	return $false
}

$rows = @()
foreach ($file in (Get-ChildItem $dlgDir -Filter *.txt | Where-Object { $_.Name -notlike '_*' } | Sort-Object Name)) {
	$scene = $file.BaseName
	foreach ($raw in (Get-Content $file.FullName)) {
		$line = $raw.Trim()
		if (-not $line.StartsWith('@')) { continue }
		$bits = $line.Substring(1).Trim() -split '\s+', 2
		$verb = $bits[0]
		$arg  = if ($bits.Count -gt 1) { $bits[1].Trim() } else { '' }
		if ($verb -eq 'img' -or $verb -eq 'image') { $kind = 'img' }
		elseif ($verb -eq 'sfx') { $kind = 'sfx' }
		elseif ($verb -eq 'music') { $kind = 'music' }
		else { continue }
		if ($skip -contains $arg.ToLower()) { continue }
		$rows += [pscustomobject]@{ Scene = $scene; Kind = $kind; Name = $arg }
	}
}

$md = @()
$md += '# Asset commission list'
$md += ''
$md += 'Generated by `Notes/commission.ps1` from the scripts in `car/vn/dialogue/`.'
$md += 'Re-run it after writing. `[x]` = exists, `[ ]` = still to make.'
$md += ''
$md += '| scene | kind | name | |'
$md += '|---|---|---|---|'
foreach ($r in ($rows | Sort-Object Scene, Kind, Name)) {
	$have = if (Test-Asset $r.Kind $r.Name) { '[x]' } else { '[ ]' }
	$md += ('| {0} | {1} | `{2}` | {3} |' -f $r.Scene, $r.Kind, $r.Name, $have)
}

$uniq = $rows | Sort-Object Kind, Name -Unique
$missing = @($uniq | Where-Object { -not (Test-Asset $_.Kind $_.Name) })
$md += ''
$md += '## Missing'
$md += ''
if ($missing.Count -eq 0) {
	$md += 'Nothing missing.'
} else {
	foreach ($k in @('img', 'sfx', 'music')) {
		$names = @($missing | Where-Object { $_.Kind -eq $k } | ForEach-Object { $_.Name })
		if ($names.Count -gt 0) {
			$where = if ($k -eq 'img') { 'car/vn/img/' } else { 'car/vn/sfx/' }
			$md += ('- **{0}** ({1}): {2}' -f $k, $where, (($names | ForEach-Object { "``$_``" }) -join ', '))
		}
	}
}

$text = ($md -join "`n")
[System.IO.File]::WriteAllText($outMd, $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output ("wrote " + $outMd)
Write-Output ("distinct assets wanted: " + $uniq.Count + "   missing: " + $missing.Count)
$missing | Sort-Object Kind, Name | ForEach-Object { Write-Output ("  MISSING {0,5}  {1}" -f $_.Kind, $_.Name) }
